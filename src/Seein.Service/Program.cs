using Seein.Core;
using Seein.Core.Hosting;
using Seein.Service;
using Microsoft.Extensions.Logging.Configuration;
using Microsoft.Extensions.Logging.EventLog;
Seein.Modularity.ModuleTransaction.Recover(Path.GetFullPath(Path.Combine(AppContext.BaseDirectory,"..")),Path.Combine(AppPaths.SystemDefault.DataRoot,"modules.json"));
var builder=Host.CreateApplicationBuilder(args);
builder.Services.AddWindowsService(options=>options.ServiceName="Seein Display Service");
LoggerProviderOptions.RegisterProviderOptions<EventLogSettings,EventLogLoggerProvider>(builder.Services);
builder.Logging.AddProvider(new RollingFileLoggerProvider(AppPaths.SystemDefault.Logs));
builder.Services.AddSingleton<PanelState>();
builder.Services.AddSingleton(_=>new ModuleSettingsStore(AppPaths.SystemDefault.Settings));
builder.Services.AddSingleton<SharedHardware>();
builder.Services.AddSingleton<ModuleServiceRegistry>();
builder.Services.AddSingleton<PanelWorker>();
builder.Services.AddSingleton<IModuleMessageBus>(p=>p.GetRequiredService<PanelWorker>());
builder.Services.Configure<HostOptions>(o=>o.BackgroundServiceExceptionBehavior=BackgroundServiceExceptionBehavior.StopHost);
builder.Services.AddHostedService(p=>p.GetRequiredService<PanelWorker>());
var host=builder.Build();
using var previewLifetime=new CancellationTokenSource();
if(AppPaths.InstanceSuffix.Length!=0&&int.TryParse(Environment.GetEnvironmentVariable("SEEIN_SMOKE_SECONDS"),out var seconds)&&seconds is >=15 and <=3600)previewLifetime.CancelAfter(TimeSpan.FromSeconds(seconds));
await host.RunAsync(previewLifetime.Token);
